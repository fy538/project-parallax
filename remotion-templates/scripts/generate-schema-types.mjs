#!/usr/bin/env node
/**
 * generate-schema-types.mjs — derive TypeScript .d.ts files from the
 * JSON Schemas that bridge Python producers and TypeScript consumers.
 *
 * Why this script exists (May 2026 audit #4 — producer→consumer drift):
 *
 *   The Python tools (tools/assembly/generate_manifest.py, tools/concepts/
 *   lookup.py, tools/asset-source/source.py) write JSON validated against
 *   the schemas under data/*.schema.json. The TypeScript consumers
 *   (FullEpisode.tsx for the assembly manifest, downstream tooling for
 *   concepts + shot lists) historically had to hand-maintain matching TS
 *   types — and they drifted. A renamed field on the Python side wouldn't
 *   surface on the TS side until a render crashed.
 *
 *   Generated .d.ts files lock the two sides to the SAME source of truth
 *   (the JSON Schema). The generated output is committed to git; CI runs
 *   this script and fails if the committed copy is out of date (catches
 *   schema edits that didn't regenerate types).
 *
 * Inputs (the cross-language seams):
 *   · data/concept-registry.schema.json     → src/types/generated/concept-registry.d.ts
 *   · data/shot-list.schema.json            → src/types/generated/shot-list.d.ts
 *   · data/predictions-log.schema.json      → src/types/generated/predictions-log.d.ts
 *   · data/visual-identity.schema.json      → src/types/generated/visual-identity.d.ts
 *
 *   Assembly-manifest schema is NOT in this set — TS consumes assembly-
 *   manifest via z.infer through Episodes/templateSchemas.ts. The JSON
 *   Schema there is for Python-side validation only (validate_data.py).
 *
 * Usage:
 *   npm run gen:types               # regenerate all
 *   npm run gen:types -- --check    # CI mode: exit 1 if anything differs
 */

import { compileFromFile } from "json-schema-to-typescript";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "fs";
import { dirname, join, basename } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const REPO_ROOT = join(ROOT, "..");
const OUT_DIR = join(ROOT, "src", "types", "generated");

const SCHEMAS = [
  {
    in: join(REPO_ROOT, "data", "concept-registry.schema.json"),
    out: "concept-registry.d.ts",
    rootType: "ConceptRegistry",
  },
  {
    in: join(REPO_ROOT, "data", "shot-list.schema.json"),
    out: "shot-list.d.ts",
    rootType: "ShotList",
  },
  {
    in: join(REPO_ROOT, "data", "predictions-log.schema.json"),
    out: "predictions-log.d.ts",
    rootType: "PredictionsLog",
  },
  {
    in: join(REPO_ROOT, "data", "visual-identity.schema.json"),
    out: "visual-identity.d.ts",
    rootType: "VisualIdentity",
  },
];

// CLI args
const args = process.argv.slice(2);
const CHECK_MODE = args.includes("--check");

// Banner prepended to every generated file. Updating the banner forces a
// regen on the next run — useful for adding doc fields without touching
// the schemas.
const BANNER_VERSION = "v1 — 2026-05-18";

const banner = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT.
 *
 * Generated by scripts/generate-schema-types.mjs from the matching JSON
 * Schema. Run \`npm run gen:types\` after editing any schema in data/*.
 *
 * Generator banner: ${BANNER_VERSION}
 */
`;

// ─── Main ──────────────────────────────────────────────────────────────────

mkdirSync(OUT_DIR, { recursive: true });

let driftCount = 0;
const results = [];

for (const { in: inputPath, out, rootType } of SCHEMAS) {
  if (!existsSync(inputPath)) {
    console.error(`  ✗ Missing schema: ${inputPath}`);
    process.exit(1);
  }

  let generated;
  try {
    generated = await compileFromFile(inputPath, {
      bannerComment: "", // we prepend our own
      style: { singleQuote: false, semi: true, trailingComma: "all" },
      // Match TS convention: PascalCase root, exact JSON property names.
      enableConstEnums: false,
      additionalProperties: false,
    });
  } catch (e) {
    console.error(`  ✗ Failed to compile ${basename(inputPath)}: ${e.message}`);
    process.exit(1);
  }

  // json-schema-to-typescript picks the root type from the schema's
  // `title` — that's usually fine. The `rootType` config is documentary
  // here (validated against the generated output below).
  const content = banner + generated;
  const outputPath = join(OUT_DIR, out);

  if (CHECK_MODE) {
    if (!existsSync(outputPath)) {
      console.error(`  ✗ ${out} missing — run \`npm run gen:types\` to create it.`);
      driftCount++;
      results.push({ out, status: "missing" });
      continue;
    }
    const current = readFileSync(outputPath, "utf-8");
    if (current !== content) {
      console.error(`  ✗ ${out} is stale — run \`npm run gen:types\` to update.`);
      driftCount++;
      results.push({ out, status: "stale" });
      continue;
    }
    console.log(`  ✓ ${out} up to date`);
    results.push({ out, status: "ok" });
  } else {
    writeFileSync(outputPath, content, "utf-8");
    console.log(`  ✓ Wrote ${out} (from ${basename(inputPath)})`);
    results.push({ out, status: "wrote" });
  }
}

// Write a small README explaining the generated/ dir.
const readmePath = join(OUT_DIR, "README.md");
const readmeContent = `# \`src/types/generated/\`

Auto-generated TypeScript type definitions from the JSON Schemas under
\`data/*.schema.json\`. **Do not edit by hand** — the next \`npm run gen:types\`
will overwrite your changes.

## When to regenerate

Whenever you edit:
- \`data/concept-registry.schema.json\`
- \`data/shot-list.schema.json\`
- \`data/predictions-log.schema.json\`
- \`data/visual-identity.schema.json\`

CI runs \`npm run gen:types -- --check\` and fails if the committed copies
are stale. Local dev workflow: edit schema → \`npm run gen:types\` → commit.

## Why these and not others

The assembly-manifest schema is NOT in this set — TypeScript consumes the
assembly manifest via \`z.infer\` through \`src/templates/Episodes/templateSchemas.ts\`.
The JSON Schema for assembly-manifest is for Python-side validation only
(\`tools/validate_data.py\`).
`;

if (!CHECK_MODE) {
  writeFileSync(readmePath, readmeContent, "utf-8");
}

if (CHECK_MODE) {
  console.log("");
  if (driftCount > 0) {
    console.error(`✗ ${driftCount} generated file(s) out of date.`);
    console.error("  Fix:  npm run gen:types  (then commit the changes)");
    process.exit(1);
  } else {
    console.log("✓ All generated files match their schemas.");
  }
} else {
  console.log("");
  console.log(`✓ Wrote ${results.filter(r => r.status === "wrote").length} type file(s) to ${OUT_DIR}`);
}
